#!/bin/sh
# Configures Google sign-in for local builds from the two public OAuth client ids.
#
#   tool/configure_google_sign_in.sh <WEB_CLIENT_ID> <IOS_CLIENT_ID>
#   tool/configure_google_sign_in.sh --fingerprints
#
# WEB_CLIENT_ID  the backend's GOOGLE_CLIENT_ID (web application client)
# IOS_CLIENT_ID  the iOS client of the SAME Google Cloud project (bundle id com.betik.mobile)
#
# Writes (both git-ignored):
#   google_sign_in.json               -> flutter run/build --dart-define-from-file=google_sign_in.json
#   ios/Flutter/GoogleSignIn.xcconfig -> GOOGLE_REVERSED_CLIENT_ID (iOS URL scheme in Info.plist)
#
# Client ids are public identifiers, not secrets. No client secret is ever needed or accepted.
# See mobile-docs/stage-3/google_sign_in_setup.md.
set -eu
cd "$(dirname "$0")/.."

fingerprints() {
  echo "Android signing certificates to register in the Android OAuth client (package com.betik.mobile):"
  if [ -f "$HOME/.android/debug.keystore" ]; then
    echo "- debug key of this machine ($HOME/.android/debug.keystore):"
    keytool -list -v -keystore "$HOME/.android/debug.keystore" -alias androiddebugkey \
      -storepass android -keypass android 2>/dev/null | grep -E 'SHA1:|SHA256:' | sed 's/^[[:space:]]*/    /'
  else
    echo "- no debug keystore yet (run a debug build once)"
  fi
  if [ -f android/key.properties ]; then
    store=$(sed -n 's/^storeFile=//p' android/key.properties)
    alias=$(sed -n 's/^keyAlias=//p' android/key.properties)
    echo "- upload key from android/key.properties ($store, alias $alias):"
    echo "    keytool -list -v -keystore \"android/app/$store\" -alias \"$alias\"   (asks for the store password)"
  else
    echo "- upload key: none configured (android/key.properties missing)"
  fi
  echo "- Play App Signing key: Play Console > Test and release > App integrity > App signing key certificate"
}

if [ "${1:-}" = "--fingerprints" ]; then fingerprints; exit 0; fi
if [ $# -ne 2 ]; then sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'; exit 2; fi

web=$1; ios=$2
pattern='^[0-9][0-9]*-[a-z0-9][a-z0-9]*\.apps\.googleusercontent\.com$'
for id in "$web" "$ios"; do
  if ! printf '%s' "$id" | grep -Eq "$pattern"; then
    echo "Not an OAuth client id: $id (expected <number>-<id>.apps.googleusercontent.com)" >&2; exit 1
  fi
done
if [ "$web" = "$ios" ]; then echo "The web and iOS client ids must differ." >&2; exit 1; fi
if [ "${web%%-*}" != "${ios%%-*}" ]; then
  echo "The two clients belong to different Google Cloud projects (${web%%-*} vs ${ios%%-*})." >&2
  echo "The backend accepts only tokens for its own web client, so both must be in that project." >&2
  exit 1
fi

reversed="com.googleusercontent.apps.${ios%.apps.googleusercontent.com}"
printf '{\n  "BETIK_GOOGLE_SERVER_CLIENT_ID": "%s",\n  "BETIK_GOOGLE_IOS_CLIENT_ID": "%s"\n}\n' "$web" "$ios" > google_sign_in.json
printf '// Generated by tool/configure_google_sign_in.sh. Not committed.\nGOOGLE_REVERSED_CLIENT_ID = %s\n' "$reversed" > ios/Flutter/GoogleSignIn.xcconfig

echo "Wrote google_sign_in.json and ios/Flutter/GoogleSignIn.xcconfig (URL scheme $reversed)."
echo "Build with: flutter run --dart-define-from-file=google_sign_in.json --dart-define=BETIK_API_URL=..."
echo
fingerprints
